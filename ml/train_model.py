"""
Train a small, explainable classifier (Random Forest) to predict whether a
resource request is likely SAFE (1) or RISKY/UNSAFE (0), using the dataset
generated by generate_dataset.py.

Proper train/test split is used; the model is only ever evaluated on the
held-out test set (see evaluate_model.py) to avoid data leakage. No deep
learning is used — a Random Forest is small, fast, and explainable enough
to discuss meaningfully in a viva.

Output: models/model.pkl  (contains the trained model + feature order)
        results/train_test_split_info.csv
"""

import csv
import os
import pickle

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split

SEED = 7
BASE = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA_PATH = os.path.join(BASE, "results", "ml_dataset.csv")
MODEL_PATH = os.path.join(BASE, "models", "model.pkl")
SPLIT_INFO_PATH = os.path.join(BASE, "results", "train_test_split_info.csv")

FEATURE_COLUMNS = [
    "held", "requested", "total_available", "remaining_need",
    "alloc_ratio", "req_ratio",
    "req_r0", "req_r1", "req_r2",
    "avail_r0", "avail_r1", "avail_r2",
]


def load_data():
    X, y = [], []
    with open(DATA_PATH, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            X.append([float(row[c]) for c in FEATURE_COLUMNS])
            y.append(int(row["label"]))
    return X, y


def main():
    X, y = load_data()
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=SEED, stratify=y
    )

    model = RandomForestClassifier(
        n_estimators=100, max_depth=8, random_state=SEED, class_weight="balanced"
    )
    model.fit(X_train, y_train)

    with open(MODEL_PATH, "wb") as f:
        pickle.dump({"model": model, "feature_names": FEATURE_COLUMNS}, f)

    # Save the exact test split so evaluate_model.py evaluates on unseen data only.
    with open(SPLIT_INFO_PATH, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(FEATURE_COLUMNS + ["label", "split"])
        for row, label in zip(X_train, y_train):
            writer.writerow(list(row) + [label, "train"])
        for row, label in zip(X_test, y_test):
            writer.writerow(list(row) + [label, "test"])

    print(f"Model trained on {len(X_train)} samples, held out {len(X_test)} test samples.")
    print(f"Saved model to {MODEL_PATH}")
    print(f"Saved split info to {SPLIT_INFO_PATH}")


if __name__ == "__main__":
    main()
